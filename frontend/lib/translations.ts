export type TranslationKey = keyof typeof vietnamese;
export type Language = "en" | "vi";
export const languageStorageKey = "woofi.language.v1";
export function readLanguage(raw: string | null, browserLanguage = "en"): Language {
  return raw === "en" || raw === "vi" ? raw : browserLanguage.toLowerCase().startsWith("vi") ? "vi" : "en";
}
export function translate(language: Language, key: TranslationKey, params: Record<string, string | number> = {}): string {
  const text = language === "vi" ? vietnamese[key] : key;
  return text.replace(/\{(\w+)\}/g, (token, name: string) => params[name] == null ? token : String(params[name]));
}
